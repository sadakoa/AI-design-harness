// One-way import from your product's code into the harness. No dependencies.
// Configure it in sync.json (see sync.example.json):
//   tokens:     copies CSS variables from your app's stylesheets into tokens.json
//               ("from" can be one file or a list; later files win, as in CSS)
//   components: lists the component files in your code in components/inventory.md
// The harness never writes back. Change the source, then run npm run sync again.
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { pathToFileURL } from "node:url";
import { renderCss, root, tokensCss, tokensJson } from "./build-tokens.mjs";

export const syncFile = join(root, "sync.json");
export const inventoryFile = join(root, "design-system/components/inventory.md");

export class MissingSource extends Error {}

const read = (path) => readFileSync(path, "utf8").replace(/\r\n/g, "\n");
const source = (from) => {
  const path = resolve(root, from);
  if (!existsSync(path)) throw new MissingSource(`can't find ${from}`);
  return path;
};

// CSS variables from every plain :root block, at the top level or inside @layer (as shadcn writes them),
// and from Tailwind v4 @theme blocks.
// Blocks inside @media or @supports, and .dark or [data-theme] blocks, are skipped: tokens.json holds one theme.
// A file with no blocks at all is read as a plain list of variables. Later values win.
// When a value is copied into tokens.json, bare HSL channels ("222.2 84% 4.9%", the shadcn style) are wrapped in hsl().
const HSL_CHANNELS = /^-?\d*\.?\d+(deg)?\s+\d*\.?\d+%\s+\d*\.?\d+%(\s*\/\s*\d*\.?\d+%?)?$/;
export const cssVariables = (css) => {
  const text = css.replace(/\/\*[\s\S]*?\*\//g, "");
  const blocks = [];
  const stack = [];
  let last = 0;
  for (let i = 0; i < text.length; i++) {
    if (text[i] === "{") {
      stack.push({ header: text.slice(last, i).split(/[;}]/).pop().trim(), start: i + 1 });
      last = i + 1;
    } else if (text[i] === "}") {
      const block = stack.pop();
      const plain = block?.header === ":root" || /^@theme\b/.test(block?.header ?? "");
      if (plain && stack.every((b) => b.header.startsWith("@layer"))) blocks.push(text.slice(block.start, i));
      last = i + 1;
    }
  }
  const vars = {};
  for (const body of blocks.length ? blocks : text.includes("{") ? [] : [text]) {
    for (const [, name, raw] of body.matchAll(/(--[\w-]+)\s*:\s*([^;{}]+?)\s*(?:;|$)/g)) {
      const value = raw.trim();
      vars[name] = value;
    }
  }
  return vars;
};

export function syncedTokens(config, current) {
  const files = [config.tokens.from].flat();
  const vars = Object.assign({}, ...files.map((from) => cssVariables(read(source(from)))));
  // Follow var() aliases inside the synced files, so a role like --surface: var(--white) gets a real value
  const resolve = (value, seen = new Set()) =>
    value.replace(/var\(\s*(--[\w-]+)\s*(?:,\s*([^)]+))?\)/g, (all, name, fallback) => {
      if (seen.has(name)) return all;
      if (name in vars) return resolve(vars[name], new Set([...seen, name]));
      return fallback ? fallback.trim() : all;
    });
  for (const name of Object.keys(vars)) vars[name] = resolve(vars[name]);
  const next = structuredClone(current);
  for (const [path, name] of Object.entries(config.tokens.map ?? {})) {
    if (!(name in vars)) throw new Error(`${name} isn't defined in ${files.join(", ")}`);
    const leaf = path.split(".").reduce((node, key) => (node[key] ??= {}), next);
    leaf.$value = HSL_CHANNELS.test(vars[name]) ? `hsl(${vars[name]})` : vars[name];
    leaf.$extensions = { ...(leaf.$extensions ?? {}), harness: { source: name } };
  }
  return next;
}

export function syncedInventory(config) {
  const dir = source(config.components.from);
  const extensions = config.components.extensions ?? [".tsx", ".jsx", ".js", ".vue", ".svelte", ".astro"];
  const files = readdirSync(dir)
    .filter((file) => extensions.some((ext) => file.endsWith(ext)) && !/\.(test|spec|stories)\./.test(file))
    .sort();
  const shown = relative(root, dir).split(sep).join("/");
  return [
    "# Component inventory",
    "",
    "> Answers: Which components exist in our code?",
    "",
    `<!-- Generated by npm run sync from ${shown}. Don't edit; change the code and run it again. -->`,
    "",
    "Use these before building anything new. Write a spec in `components/<name>.md` only when a component needs rules beyond its code.",
    "",
    "| Component | File |",
    "|---|---|",
    ...files.map((file) => `| ${file.replace(/\.[^.]+$/, "")} | \`${shown}/${file}\` |`),
    "",
  ].join("\n");
}

export const readConfig = () => (existsSync(syncFile) ? JSON.parse(read(syncFile)) : null);

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const config = readConfig();
  if (!config) {
    console.log("No sync.json, so there's nothing to sync. See https://github.com/sadakoa/AI-design-harness/blob/main/docs/adopting.md");
    process.exit(0);
  }
  try {
    if (config.tokens) {
      const tokens = syncedTokens(config, JSON.parse(read(tokensJson)));
      writeFileSync(tokensJson, JSON.stringify(tokens, null, 2) + "\n");
      writeFileSync(tokensCss, renderCss(tokens));
      console.log(`Synced ${Object.keys(config.tokens.map ?? {}).length} tokens from ${[config.tokens.from].flat().join(", ")}`);
    }
    if (config.components) {
      const inventory = syncedInventory(config);
      mkdirSync(dirname(inventoryFile), { recursive: true });
      writeFileSync(inventoryFile, inventory);
      console.log(`Listed ${inventory.split("\n").filter((l) => l.startsWith("| ") && !l.startsWith("| Component")).length} components from ${config.components.from}`);
    }
  } catch (error) {
    console.error(`error  ${error.message}`);
    process.exit(1);
  }
}
